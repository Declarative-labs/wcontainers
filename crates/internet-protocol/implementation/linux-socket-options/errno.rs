/// Gives the kernel interface's name of a Linux error number, none for a number it does not name.
pub fn errno_of(number: i32) -> Option<Errno> {
    NAMED
        .iter()
        .copied()
        .find(|errno| i32::from(*errno as u16) == number)
}
