//! The bugs the independent checks planted in these models, each behind one switch so that a run turns on exactly one.
//!
//! A model reads `is` where a bug would change it. Without the `planted` feature every switch is off and the check
//! costs nothing; with it, `plant` turns one bug on for the whole process, so only a test or a check sets it.

use core::convert::Infallible;

use crate::Instruction;

/// Which check planted a bug: the first and second passes' checks, the check of the cut, the fourth check and the sync
/// with the expectations, which added the random number registers and the behavior of a chip without a feature.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug)]
pub enum PlantedBy {
    First,
    Second,
    CutCheck,
    FourthCheck,
    Sync,
    /// The second half of the SVE work list, whose bugs are numbered from 2001.
    ScalableSecondHalf,
}

/// One planted bug: its number, the instruction whose states must catch it, and what it does.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct PlantedBug {
    pub number: u32,
    pub instruction: Instruction<Infallible>,
    pub planted_by: PlantedBy,
    pub what: &'static str,
}

#[cfg(feature = "planted")]
static PLANTED: core::sync::atomic::AtomicU32 = core::sync::atomic::AtomicU32::new(NONE);

/// The number no bug has: every model as written.
pub const NONE: u32 = 0;

/// Whether the bug is the one planted.
#[cfg(feature = "planted")]
pub fn is(bug: u32) -> bool {
    PLANTED.load(core::sync::atomic::Ordering::Relaxed) == bug
}

/// Whether the bug is the one planted: never, without the `planted` feature.
#[cfg(not(feature = "planted"))]
pub const fn is(_: u32) -> bool {
    false
}

/// Whether one of the bugs is the one planted.
pub fn any(bugs: &[u32]) -> bool {
    bugs.iter().any(|bug| is(*bug))
}

/// Turns on the bug, or with [`NONE`] every model as written.
#[cfg(feature = "planted")]
pub fn plant(bug: u32) {
    PLANTED.store(bug, core::sync::atomic::Ordering::Relaxed);
}

