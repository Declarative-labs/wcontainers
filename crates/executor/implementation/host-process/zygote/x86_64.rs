//! The zygote's code for x86-64 hosts.

use linux_raw_sys::general as linux;

use super::frame::{
    BUFFER, FRAME, IOVEC, IOVEC_LENGTH, MESSAGE_HEADER, MESSAGE_IOVEC, MESSAGE_IOVEC_COUNT,
};
use super::frame::{OWN_AREA, STATUS, VALUE};
use super::{MESSAGE, RSEQ_AREA, RSEQ_FLAG_UNREGISTER, RSEQ_SIG, Request, ZygoteEnd};
use crate::layout::{ZYGOTE, ZYGOTE_CODE_SIZE, ZYGOTE_SIZE};

// Entered in the fork child with rdi the code's memfd, rsi the socket, rdx and rcx the inherited restartable-sequences
// area's offset from the thread pointer and its size (0 for none), r8 the user-space top. glibc's thread pointer is
// the word at fs:0.
core::arch::global_asm!(
    ".pushsection .text.wcontainers_host_process_zygote,\"ax\",@progbits",
    ".balign 16",
    ".globl wcontainers_host_process_zygote_start",
    ".hidden wcontainers_host_process_zygote_start",
    "wcontainers_host_process_zygote_start:",
    ".Lwchp_start:",
    "mov r15, rdi",
    "mov rbp, rsi",
    "mov r12, rdx",
    "mov r13, rcx",
    "mov r14, r8",
    // The code, read-execute from its memfd, over the embedder's reservation.
    "mov rdi, {zygote}",
    "mov esi, {code_size}",
    "mov edx, {prot_code}",
    "mov r10d, {map_code}",
    "mov r8, r15",
    "xor r9d, r9d",
    "mov eax, {nr_mmap}",
    "syscall",
    "mov rcx, {zygote}",
    "cmp rax, rcx",
    "jne .Lwchp_pages_refused",
    // The stack, after the code.
    "mov rdi, {zygote}",
    "add rdi, {code_size}",
    "mov esi, {stack_size}",
    "mov edx, {prot_stack}",
    "mov r10d, {map_stack}",
    "mov r8, -1",
    "xor r9d, r9d",
    "mov eax, {nr_mmap}",
    "syscall",
    "mov rcx, {zygote}",
    "add rcx, {code_size}",
    "cmp rax, rcx",
    "jne .Lwchp_pages_refused",
    "mov rdi, r15",
    "mov eax, {nr_close}",
    "syscall",
    // Continue in the copy.
    "lea r9, [rip + .Lwchp_mapped]",
    "lea r10, [rip + .Lwchp_start]",
    "sub r9, r10",
    "mov r10, {zygote}",
    "add r9, r10",
    "jmp r9",
    ".Lwchp_mapped:",
    "mov rsp, {zygote}",
    "add rsp, {zygote_size} - {frame}",
    "mov eax, {nr_getpid}",
    "syscall",
    "mov rbx, rax",
    // Drop the forking thread's restartable-sequences area, then prove none is left by registering our own.
    "test r13, r13",
    "jz .Lwchp_unregistered",
    "mov rdi, qword ptr fs:[0]",
    "add rdi, r12",
    "mov esi, r13d",
    "mov edx, {unregister}",
    "mov r10d, {sig}",
    "mov eax, {nr_rseq}",
    "syscall",
    "test rax, rax",
    "jnz .Lwchp_not_unregistered",
    ".Lwchp_unregistered:",
    "lea r15, [rsp + {own_area}]",
    "xor eax, eax",
    "mov qword ptr [r15], rax",
    "mov qword ptr [r15 + 8], rax",
    "mov qword ptr [r15 + 16], rax",
    "mov qword ptr [r15 + 24], rax",
    "mov rdi, r15",
    "mov esi, {rseq_area}",
    "xor edx, edx",
    "mov r10d, {sig}",
    "mov eax, {nr_rseq}",
    "syscall",
    "test rax, rax",
    "jnz .Lwchp_left_registered",
    "mov rdi, r15",
    "mov esi, {rseq_area}",
    "mov edx, {unregister}",
    "mov r10d, {sig}",
    "mov eax, {nr_rseq}",
    "syscall",
    "test rax, rax",
    "jnz .Lwchp_left_registered",
    "xor edi, edi",
    "mov esi, {robust_size}",
    "mov eax, {nr_set_robust_list}",
    "syscall",
    "xor edi, edi",
    "mov eax, {nr_set_tid_address}",
    "syscall",
    // Every descriptor but the socket.
    "test rbp, rbp",
    "jz .Lwchp_low_closed",
    "xor edi, edi",
    "lea rsi, [rbp - 1]",
    "xor edx, edx",
    "mov eax, {nr_close_range}",
    "syscall",
    "test rax, rax",
    "jnz .Lwchp_descriptors",
    ".Lwchp_low_closed:",
    "lea rdi, [rbp + 1]",
    "mov esi, -1",
    "xor edx, edx",
    "mov eax, {nr_close_range}",
    "syscall",
    "test rax, rax",
    "jnz .Lwchp_descriptors",
    // Every mapping below and above our own pages.
    "xor edi, edi",
    "mov rsi, {zygote}",
    "mov eax, {nr_munmap}",
    "syscall",
    "test rax, rax",
    "jnz .Lwchp_unmap",
    "mov rdi, {zygote}",
    "add rdi, {zygote_size}",
    "mov rsi, r14",
    "sub rsi, rdi",
    "mov eax, {nr_munmap}",
    "syscall",
    "test rax, rax",
    "jnz .Lwchp_unmap",
    // One message header for every request and answer.
    "lea rax, [rsp + {buffer}]",
    "mov qword ptr [rsp + {iovec}], rax",
    "mov qword ptr [rsp + {iovec_length}], {message}",
    "xor eax, eax",
    "mov qword ptr [rsp + {header}], rax",
    "mov qword ptr [rsp + {header} + 8], rax",
    "mov qword ptr [rsp + {header} + 16], rax",
    "mov qword ptr [rsp + {header} + 24], rax",
    "mov qword ptr [rsp + {header} + 32], rax",
    "mov qword ptr [rsp + {header} + 40], rax",
    "mov qword ptr [rsp + {header} + 48], rax",
    "lea rax, [rsp + {iovec}]",
    "mov qword ptr [rsp + {header_iovec}], rax",
    "mov qword ptr [rsp + {header_iovec_count}], 1",
    ".Lwchp_next:",
    "mov rdi, rbp",
    "lea rsi, [rsp + {header}]",
    "xor edx, edx",
    "mov eax, {nr_recvmsg}",
    "syscall",
    "test rax, rax",
    "jz .Lwchp_embedder_gone",
    "cmp rax, {message}",
    "jne .Lwchp_bad_request",
    "mov rax, qword ptr [rsp + {buffer}]",
    "cmp rax, {ping}",
    "je .Lwchp_ping",
    "cmp rax, {fork}",
    "je .Lwchp_fork",
    "cmp rax, {kill}",
    "je .Lwchp_kill",
    "cmp rax, {reap}",
    "je .Lwchp_reap",
    "jmp .Lwchp_bad_request",
    ".Lwchp_ping:",
    "xor eax, eax",
    ".Lwchp_answer:",
    "mov qword ptr [rsp + {value}], rax",
    "mov rdi, rbp",
    "lea rsi, [rsp + {header}]",
    "xor edx, edx",
    "mov eax, {nr_sendmsg}",
    "syscall",
    "cmp rax, {message}",
    "jne .Lwchp_answer_refused",
    "jmp .Lwchp_next",
    ".Lwchp_fork:",
    "mov edi, {sigchld}",
    "xor esi, esi",
    "xor edx, edx",
    "xor r10d, r10d",
    "xor r8d, r8d",
    "mov eax, {nr_clone}",
    "syscall",
    "test rax, rax",
    "jz .Lwchp_stub",
    "jmp .Lwchp_answer",
    ".Lwchp_kill:",
    "mov rdi, qword ptr [rsp + {value}]",
    "mov esi, {sigkill}",
    "mov eax, {nr_kill}",
    "syscall",
    "jmp .Lwchp_answer",
    ".Lwchp_reap:",
    "mov rdi, qword ptr [rsp + {value}]",
    "lea rsi, [rsp + {status}]",
    "xor edx, edx",
    "xor r10d, r10d",
    "mov eax, {nr_wait4}",
    "syscall",
    "test rax, rax",
    "js .Lwchp_answer",
    "mov eax, dword ptr [rsp + {status}]",
    "jmp .Lwchp_answer",
    // A stub: it leaves the zygote's socket, dies with the zygote, and waits.
    ".Lwchp_stub:",
    "mov rdi, rbp",
    "mov eax, {nr_close}",
    "syscall",
    "mov edi, {pdeathsig}",
    "mov esi, {sigkill}",
    "mov eax, {nr_prctl}",
    "syscall",
    "mov eax, {nr_getppid}",
    "syscall",
    "cmp rax, rbx",
    "jne .Lwchp_orphaned",
    ".Lwchp_stub_wait:",
    "mov dword ptr [rsp + {status}], 0",
    "lea rdi, [rsp + {status}]",
    "mov esi, {futex_wait}",
    "xor edx, edx",
    "xor r10d, r10d",
    "mov eax, {nr_futex}",
    "syscall",
    "jmp .Lwchp_stub_wait",
    ".Lwchp_pages_refused:",
    "mov edi, {end_pages}",
    "jmp .Lwchp_exit",
    ".Lwchp_not_unregistered:",
    "mov edi, {end_not_unregistered}",
    "jmp .Lwchp_exit",
    ".Lwchp_left_registered:",
    "mov edi, {end_left_registered}",
    "jmp .Lwchp_exit",
    ".Lwchp_descriptors:",
    "mov edi, {end_descriptors}",
    "jmp .Lwchp_exit",
    ".Lwchp_unmap:",
    "mov edi, {end_unmap}",
    "jmp .Lwchp_exit",
    ".Lwchp_bad_request:",
    "mov edi, {end_bad_request}",
    "jmp .Lwchp_exit",
    ".Lwchp_answer_refused:",
    "mov edi, {end_answer}",
    "jmp .Lwchp_exit",
    ".Lwchp_orphaned:",
    "mov edi, {end_orphaned}",
    "jmp .Lwchp_exit",
    ".Lwchp_embedder_gone:",
    "mov edi, {end_gone}",
    ".Lwchp_exit:",
    "mov eax, {nr_exit_group}",
    "syscall",
    "jmp .Lwchp_exit",
    ".globl wcontainers_host_process_zygote_end",
    ".hidden wcontainers_host_process_zygote_end",
    "wcontainers_host_process_zygote_end:",
    ".popsection",
    zygote = const ZYGOTE,
    code_size = const ZYGOTE_CODE_SIZE,
    stack_size = const ZYGOTE_SIZE - ZYGOTE_CODE_SIZE,
    zygote_size = const ZYGOTE_SIZE,
    frame = const FRAME,
    prot_code = const linux::PROT_READ | linux::PROT_EXEC,
    map_code = const linux::MAP_SHARED | linux::MAP_FIXED,
    prot_stack = const linux::PROT_READ | linux::PROT_WRITE,
    map_stack = const linux::MAP_PRIVATE | linux::MAP_ANONYMOUS | linux::MAP_FIXED,
    unregister = const RSEQ_FLAG_UNREGISTER,
    sig = const RSEQ_SIG,
    rseq_area = const RSEQ_AREA,
    own_area = const OWN_AREA,
    robust_size = const size_of::<linux::robust_list_head>(),
    buffer = const BUFFER,
    value = const VALUE,
    iovec = const IOVEC,
    iovec_length = const IOVEC_LENGTH,
    header = const MESSAGE_HEADER,
    header_iovec = const MESSAGE_IOVEC,
    header_iovec_count = const MESSAGE_IOVEC_COUNT,
    status = const STATUS,
    message = const MESSAGE,
    ping = const Request::Ping as u64,
    fork = const Request::Fork as u64,
    kill = const Request::Kill as u64,
    reap = const Request::Reap as u64,
    sigchld = const linux::SIGCHLD,
    sigkill = const linux::SIGKILL,
    pdeathsig = const linux_raw_sys::prctl::PR_SET_PDEATHSIG,
    futex_wait = const linux::FUTEX_WAIT_PRIVATE,
    end_pages = const ZygoteEnd::PagesRefused as u8,
    end_not_unregistered = const ZygoteEnd::RestartableSequencesNotUnregistered as u8,
    end_left_registered = const ZygoteEnd::RestartableSequencesLeftRegistered as u8,
    end_descriptors = const ZygoteEnd::DescriptorsNotClosed as u8,
    end_unmap = const ZygoteEnd::UnmapRefused as u8,
    end_bad_request = const ZygoteEnd::BadRequest as u8,
    end_answer = const ZygoteEnd::AnswerRefused as u8,
    end_orphaned = const ZygoteEnd::Orphaned as u8,
    end_gone = const ZygoteEnd::EmbedderGone as u8,
    nr_mmap = const linux::__NR_mmap,
    nr_close = const linux::__NR_close,
    nr_getpid = const linux::__NR_getpid,
    nr_rseq = const linux::__NR_rseq,
    nr_set_robust_list = const linux::__NR_set_robust_list,
    nr_set_tid_address = const linux::__NR_set_tid_address,
    nr_close_range = const linux::__NR_close_range,
    nr_munmap = const linux::__NR_munmap,
    nr_recvmsg = const linux::__NR_recvmsg,
    nr_sendmsg = const linux::__NR_sendmsg,
    nr_clone = const linux::__NR_clone,
    nr_kill = const linux::__NR_kill,
    nr_wait4 = const linux::__NR_wait4,
    nr_prctl = const linux::__NR_prctl,
    nr_getppid = const linux::__NR_getppid,
    nr_futex = const linux::__NR_futex,
    nr_exit_group = const linux::__NR_exit_group,
);
