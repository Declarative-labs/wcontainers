//! The zygote's code for ARM64 hosts.

use linux_raw_sys::general as linux;

use super::frame::{
    BUFFER, FRAME, IOVEC, IOVEC_LENGTH, MESSAGE_HEADER, MESSAGE_IOVEC, MESSAGE_IOVEC_COUNT,
};
use super::frame::{OWN_AREA, STATUS, VALUE};
use super::{MESSAGE, RSEQ_AREA, RSEQ_FLAG_UNREGISTER, RSEQ_SIG, Request, ZygoteEnd};
use crate::layout::{ZYGOTE, ZYGOTE_CODE_SIZE, ZYGOTE_SIZE};

// Entered in the fork child with x0 the code's memfd, x1 the socket, x2 and x3 the inherited restartable-sequences
// area's offset from the thread pointer and its size (0 for none), x4 the user-space top.
core::arch::global_asm!(
    ".pushsection .text.wcontainers_host_process_zygote,\"ax\",%progbits",
    ".balign 16",
    ".globl wcontainers_host_process_zygote_start",
    ".hidden wcontainers_host_process_zygote_start",
    "wcontainers_host_process_zygote_start:",
    ".Lwchp_start:",
    "mov x24, x0",
    "mov x20, x1",
    "mov x21, x2",
    "mov x22, x3",
    "mov x23, x4",
    // The code, read-execute from its memfd, over the embedder's reservation.
    "mov x0, #{zygote}",
    "mov x1, #{code_size}",
    "mov x2, #{prot_code}",
    "mov x3, #{map_code}",
    "mov x4, x24",
    "mov x5, #0",
    "mov x8, #{nr_mmap}",
    "svc #0",
    "mov x9, #{zygote}",
    "cmp x0, x9",
    "b.ne .Lwchp_pages_refused",
    // The stack, after the code.
    "add x0, x9, #{code_size}",
    "mov x1, #{stack_size}",
    "mov x2, #{prot_stack}",
    "mov x3, #{map_stack}",
    "mov x4, #-1",
    "mov x5, #0",
    "mov x8, #{nr_mmap}",
    "svc #0",
    "add x9, x9, #{code_size}",
    "cmp x0, x9",
    "b.ne .Lwchp_pages_refused",
    "mov x0, x24",
    "mov x8, #{nr_close}",
    "svc #0",
    // Continue in the copy.
    "adr x9, .Lwchp_mapped",
    "adr x10, .Lwchp_start",
    "sub x9, x9, x10",
    "mov x10, #{zygote}",
    "add x9, x9, x10",
    "br x9",
    ".Lwchp_mapped:",
    "mov x9, #{zygote}",
    "add x9, x9, #{zygote_size}",
    "sub sp, x9, #{frame}",
    "mov x8, #{nr_getpid}",
    "svc #0",
    "mov x19, x0",
    // Drop the forking thread's restartable-sequences area, then prove none is left by registering our own.
    "cbz x22, .Lwchp_unregistered",
    "mrs x0, tpidr_el0",
    "add x0, x0, x21",
    "mov x1, x22",
    "mov x2, #{unregister}",
    "movz w3, #{sig_low}",
    "movk w3, #{sig_high}, lsl #16",
    "mov x8, #{nr_rseq}",
    "svc #0",
    "cbnz x0, .Lwchp_not_unregistered",
    ".Lwchp_unregistered:",
    "add x25, sp, #{own_area}",
    "stp xzr, xzr, [x25]",
    "stp xzr, xzr, [x25, #16]",
    "mov x0, x25",
    "mov x1, #{rseq_area}",
    "mov x2, #0",
    "movz w3, #{sig_low}",
    "movk w3, #{sig_high}, lsl #16",
    "mov x8, #{nr_rseq}",
    "svc #0",
    "cbnz x0, .Lwchp_left_registered",
    "mov x0, x25",
    "mov x1, #{rseq_area}",
    "mov x2, #{unregister}",
    "movz w3, #{sig_low}",
    "movk w3, #{sig_high}, lsl #16",
    "mov x8, #{nr_rseq}",
    "svc #0",
    "cbnz x0, .Lwchp_left_registered",
    "mov x0, #0",
    "mov x1, #{robust_size}",
    "mov x8, #{nr_set_robust_list}",
    "svc #0",
    "mov x0, #0",
    "mov x8, #{nr_set_tid_address}",
    "svc #0",
    // Every descriptor but the socket.
    "cbz x20, .Lwchp_low_closed",
    "mov x0, #0",
    "sub x1, x20, #1",
    "mov x2, #0",
    "mov x8, #{nr_close_range}",
    "svc #0",
    "cbnz x0, .Lwchp_descriptors",
    ".Lwchp_low_closed:",
    "add x0, x20, #1",
    "mov w1, #-1",
    "mov x2, #0",
    "mov x8, #{nr_close_range}",
    "svc #0",
    "cbnz x0, .Lwchp_descriptors",
    // Every mapping below and above our own pages.
    "mov x0, #0",
    "mov x1, #{zygote}",
    "mov x8, #{nr_munmap}",
    "svc #0",
    "cbnz x0, .Lwchp_unmap",
    "mov x0, #{zygote}",
    "add x0, x0, #{zygote_size}",
    "sub x1, x23, x0",
    "mov x8, #{nr_munmap}",
    "svc #0",
    "cbnz x0, .Lwchp_unmap",
    // One message header for every request and answer.
    "add x9, sp, #{buffer}",
    "str x9, [sp, #{iovec}]",
    "mov x9, #{message}",
    "str x9, [sp, #{iovec_length}]",
    "add x9, sp, #{header}",
    "stp xzr, xzr, [x9]",
    "stp xzr, xzr, [x9, #16]",
    "stp xzr, xzr, [x9, #32]",
    "str xzr, [x9, #48]",
    "add x9, sp, #{iovec}",
    "str x9, [sp, #{header_iovec}]",
    "mov x9, #1",
    "str x9, [sp, #{header_iovec_count}]",
    ".Lwchp_next:",
    "mov x0, x20",
    "add x1, sp, #{header}",
    "mov x2, #0",
    "mov x8, #{nr_recvmsg}",
    "svc #0",
    "cbz x0, .Lwchp_embedder_gone",
    "cmp x0, #{message}",
    "b.ne .Lwchp_bad_request",
    "ldr x9, [sp, #{buffer}]",
    "ldr x10, [sp, #{value}]",
    "cmp x9, #{ping}",
    "b.eq .Lwchp_ping",
    "cmp x9, #{fork}",
    "b.eq .Lwchp_fork",
    "cmp x9, #{kill}",
    "b.eq .Lwchp_kill",
    "cmp x9, #{reap}",
    "b.eq .Lwchp_reap",
    "b .Lwchp_bad_request",
    ".Lwchp_ping:",
    "mov x0, #0",
    ".Lwchp_answer:",
    "str x0, [sp, #{value}]",
    "mov x0, x20",
    "add x1, sp, #{header}",
    "mov x2, #0",
    "mov x8, #{nr_sendmsg}",
    "svc #0",
    "cmp x0, #{message}",
    "b.ne .Lwchp_answer_refused",
    "b .Lwchp_next",
    ".Lwchp_fork:",
    "mov x0, #{sigchld}",
    "mov x1, #0",
    "mov x2, #0",
    "mov x3, #0",
    "mov x4, #0",
    "mov x8, #{nr_clone}",
    "svc #0",
    "cbz x0, .Lwchp_stub",
    "b .Lwchp_answer",
    ".Lwchp_kill:",
    "mov x0, x10",
    "mov x1, #{sigkill}",
    "mov x8, #{nr_kill}",
    "svc #0",
    "b .Lwchp_answer",
    ".Lwchp_reap:",
    "mov x0, x10",
    "add x1, sp, #{status}",
    "mov x2, #0",
    "mov x3, #0",
    "mov x8, #{nr_wait4}",
    "svc #0",
    "tbnz x0, #63, .Lwchp_answer",
    "ldr w0, [sp, #{status}]",
    "b .Lwchp_answer",
    // A stub: it leaves the zygote's socket, dies with the zygote, and waits.
    ".Lwchp_stub:",
    "mov x0, x20",
    "mov x8, #{nr_close}",
    "svc #0",
    "mov x0, #{pdeathsig}",
    "mov x1, #{sigkill}",
    "mov x8, #{nr_prctl}",
    "svc #0",
    "mov x8, #{nr_getppid}",
    "svc #0",
    "cmp x0, x19",
    "b.ne .Lwchp_orphaned",
    ".Lwchp_stub_wait:",
    "str wzr, [sp, #{status}]",
    "add x0, sp, #{status}",
    "mov x1, #{futex_wait}",
    "mov x2, #0",
    "mov x3, #0",
    "mov x8, #{nr_futex}",
    "svc #0",
    "b .Lwchp_stub_wait",
    ".Lwchp_pages_refused:",
    "mov x0, #{end_pages}",
    "b .Lwchp_exit",
    ".Lwchp_not_unregistered:",
    "mov x0, #{end_not_unregistered}",
    "b .Lwchp_exit",
    ".Lwchp_left_registered:",
    "mov x0, #{end_left_registered}",
    "b .Lwchp_exit",
    ".Lwchp_descriptors:",
    "mov x0, #{end_descriptors}",
    "b .Lwchp_exit",
    ".Lwchp_unmap:",
    "mov x0, #{end_unmap}",
    "b .Lwchp_exit",
    ".Lwchp_bad_request:",
    "mov x0, #{end_bad_request}",
    "b .Lwchp_exit",
    ".Lwchp_answer_refused:",
    "mov x0, #{end_answer}",
    "b .Lwchp_exit",
    ".Lwchp_orphaned:",
    "mov x0, #{end_orphaned}",
    "b .Lwchp_exit",
    ".Lwchp_embedder_gone:",
    "mov x0, #{end_gone}",
    ".Lwchp_exit:",
    "mov x8, #{nr_exit_group}",
    "svc #0",
    "b .Lwchp_exit",
    ".globl wcontainers_host_process_zygote_end",
    ".hidden wcontainers_host_process_zygote_end",
    "wcontainers_host_process_zygote_end:",
    ".popsection",
    zygote = const ZYGOTE,
    code_size = const ZYGOTE_CODE_SIZE,
    stack_size = const ZYGOTE_SIZE - ZYGOTE_CODE_SIZE,
    zygote_size = const ZYGOTE_SIZE,
    frame = const FRAME,
    prot_code = const linux::PROT_READ | linux::PROT_EXEC,
    map_code = const linux::MAP_SHARED | linux::MAP_FIXED,
    prot_stack = const linux::PROT_READ | linux::PROT_WRITE,
    map_stack = const linux::MAP_PRIVATE | linux::MAP_ANONYMOUS | linux::MAP_FIXED,
    unregister = const RSEQ_FLAG_UNREGISTER,
    sig_low = const RSEQ_SIG & 0xffff,
    sig_high = const RSEQ_SIG >> 16,
    rseq_area = const RSEQ_AREA,
    own_area = const OWN_AREA,
    robust_size = const size_of::<linux::robust_list_head>(),
    buffer = const BUFFER,
    value = const VALUE,
    iovec = const IOVEC,
    iovec_length = const IOVEC_LENGTH,
    header = const MESSAGE_HEADER,
    header_iovec = const MESSAGE_IOVEC,
    header_iovec_count = const MESSAGE_IOVEC_COUNT,
    status = const STATUS,
    message = const MESSAGE,
    ping = const Request::Ping as u64,
    fork = const Request::Fork as u64,
    kill = const Request::Kill as u64,
    reap = const Request::Reap as u64,
    sigchld = const linux::SIGCHLD,
    sigkill = const linux::SIGKILL,
    pdeathsig = const linux_raw_sys::prctl::PR_SET_PDEATHSIG,
    futex_wait = const linux::FUTEX_WAIT_PRIVATE,
    end_pages = const ZygoteEnd::PagesRefused as u8,
    end_not_unregistered = const ZygoteEnd::RestartableSequencesNotUnregistered as u8,
    end_left_registered = const ZygoteEnd::RestartableSequencesLeftRegistered as u8,
    end_descriptors = const ZygoteEnd::DescriptorsNotClosed as u8,
    end_unmap = const ZygoteEnd::UnmapRefused as u8,
    end_bad_request = const ZygoteEnd::BadRequest as u8,
    end_answer = const ZygoteEnd::AnswerRefused as u8,
    end_orphaned = const ZygoteEnd::Orphaned as u8,
    end_gone = const ZygoteEnd::EmbedderGone as u8,
    nr_mmap = const linux::__NR_mmap,
    nr_close = const linux::__NR_close,
    nr_getpid = const linux::__NR_getpid,
    nr_rseq = const linux::__NR_rseq,
    nr_set_robust_list = const linux::__NR_set_robust_list,
    nr_set_tid_address = const linux::__NR_set_tid_address,
    nr_close_range = const linux::__NR_close_range,
    nr_munmap = const linux::__NR_munmap,
    nr_recvmsg = const linux::__NR_recvmsg,
    nr_sendmsg = const linux::__NR_sendmsg,
    nr_clone = const linux::__NR_clone,
    nr_kill = const linux::__NR_kill,
    nr_wait4 = const linux::__NR_wait4,
    nr_prctl = const linux::__NR_prctl,
    nr_getppid = const linux::__NR_getppid,
    nr_futex = const linux::__NR_futex,
    nr_exit_group = const linux::__NR_exit_group,
);
