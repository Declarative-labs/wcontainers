/// The first record of a signal frame's extra space on ARM64, the FP/SIMD registers: Linux's `struct fpsimd_context`
/// (arch/arm64/include/uapi/asm/sigcontext.h), which neither libc nor linux-raw-sys defines.
#[repr(C)]
struct FpsimdContext {
    magic: u32,
    size: u32,
    fpsr: u32,
    fpcr: u32,
    vregs: [u128; 32],
}

/// `FPSIMD_MAGIC`, the same header's tag of that record.
const FPSIMD_MAGIC: u32 = 0x4650_8001;

/// Where a signal frame's general registers start, then sp, pc and pstate, as a register block holds them.
const UC_REGS: usize =
    offset_of!(libc::ucontext_t, uc_mcontext) + offset_of!(libc::mcontext_t, regs);

/// The words copied from the frame into a register block: x0 to x30, sp, pc and pstate.
const FRAME_WORDS: usize = offset_of!(RegisterBlock, pstate) / size_of::<u64>() + 1;

/// Where the frame's extra space starts: after pstate, aligned as its records (`__reserved` in Linux's `struct
/// sigcontext`).
const UC_RESERVED: usize = offset_of!(libc::ucontext_t, uc_mcontext)
    + (offset_of!(libc::mcontext_t, pstate) + size_of::<u64>())
        .next_multiple_of(align_of::<FpsimdContext>());

const _: () = assert!(
    offset_of!(libc::mcontext_t, sp) - offset_of!(libc::mcontext_t, regs)
        == offset_of!(RegisterBlock, sp)
        && offset_of!(libc::mcontext_t, pc) - offset_of!(libc::mcontext_t, regs)
            == offset_of!(RegisterBlock, pc)
        && offset_of!(libc::mcontext_t, pstate) - offset_of!(libc::mcontext_t, regs)
            == offset_of!(RegisterBlock, pstate)
        && offset_of!(RegisterBlock, x) == 0
        && FRAME_WORDS.is_multiple_of(2)
        && offset_of!(RegisterBlock, fpcr) == offset_of!(RegisterBlock, fpsr) + size_of::<u32>()
        && offset_of!(FpsimdContext, fpcr) == offset_of!(FpsimdContext, fpsr) + size_of::<u32>()
        && (register::REGISTERS + offset_of!(RegisterBlock, fpsr)).is_multiple_of(size_of::<u64>())
        && (register::REGISTERS + offset_of!(RegisterBlock, v)).is_multiple_of(16)
        && UC_RESERVED + size_of::<FpsimdContext>()
            <= offset_of!(libc::ucontext_t, uc_mcontext) + size_of::<libc::mcontext_t>()
);

