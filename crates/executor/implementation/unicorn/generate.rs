//! Produces the kernel's Linux definitions from linux-raw-sys's ARM64 bindings.
//!
//! linux-raw-sys picks its bindings by the target it is built for, and the kernel is also built for
//! wasm32, so the kernel carries a copy of the ARM64 files instead. In the copy every guest pointer and
//! every `usize` field is a `u64`, which is what it is on ARM64, so layouts are the same on every target.

use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use regex::Regex;

/// The linux-raw-sys modules the kernel uses; its error numbers are the kernel interface's.
const MODULES: &[&str] = &[
    "general", "auxvec", "system", "ioctl", "prctl", "net", "ptrace", "netlink", "if_arp",
    "elf_uapi",
];

/// Structures the kernel copies to or from guest memory. They get zerocopy's byte conversions, whose
/// derive also proves they have no padding.
const BYTES: &[&str] = &[
    "prctl_mm_map",
    "elf64_hdr",
    "elf64_phdr",
    "elf64_note",
    "stat",
    "statx",
    "statx_timestamp",
    "statfs",
    "__kernel_fsid_t",
    "__kernel_timespec",
    "timespec",
    "__kernel_old_timeval",
    "timeval",
    "timezone",
    "__kernel_itimerspec",
    "new_utsname",
    "rlimit",
    "rlimit64",
    "rusage",
    "iovec",
    "winsize",
    "kernel_sigaction",
    "open_how",
    "kernel_sigset_t",
    "__user_cap_header_struct",
    "__user_cap_data_struct",
    "sock_filter",
    "seccomp_data",
    "seccomp_notif_sizes",
    "cachestat_range",
    "cachestat",
    "fsxattr",
    "file_clone_range",
    "fsuuid2",
    "termios",
    "termios2",
    "futex_waitv",
    "__kernel_old_itimerval",
    "itimerval",
    "user_fpsimd_state",
];

/// One file the generator writes, relative to the workspace root, and what it holds.
pub struct Generated {
    pub path: PathBuf,
    pub contents: String,
}

/// How many folders this crate sits below the workspace root (crates/executor/implementation/unicorn).
const FOLDERS_BELOW_ROOT: usize = 4;

/// The workspace root.
pub fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(FOLDERS_BELOW_ROOT)
        .expect("the test crate sits four levels below the workspace root")
        .to_path_buf()
}

/// The source directory of the linux-raw-sys version this workspace locks.
fn linux_raw_sys_source() -> (PathBuf, String) {
    let metadata = cargo_metadata::MetadataCommand::new()
        .manifest_path(workspace_root().join("Cargo.toml"))
        .exec()
        .expect("cargo metadata");
    let package = metadata
        .packages
        .iter()
        .filter(|package| package.name.as_str() == "linux-raw-sys")
        .max_by_key(|package| package.version.clone())
        .expect("linux-raw-sys is a dependency of the test crate");
    let directory = package
        .manifest_path
        .parent()
        .expect("manifest has a directory")
        .as_std_path()
        .join("src")
        .join("aarch64");
    (directory, package.version.to_string())
}

/// The kernel's source folder, relative to the workspace root.
const KERNEL_SOURCE: &str = "crates/kernel/implementation/linux";

/// The layout test the generator writes, relative to the workspace root.
const LAYOUT_TEST: &str = "crates/executor/implementation/unicorn/tests/linux_layouts.rs";

/// The package whose program writes the generated files.
const PACKAGE: &str = env!("CARGO_PKG_NAME");

/// Every file the generator owns, with the contents it should have.
pub fn generate() -> Vec<Generated> {
    let (source, version) = linux_raw_sys_source();
    let kernel = workspace_root().join(KERNEL_SOURCE);
    let interface = interface_names();
    let mut out = Vec::new();
    let mut structs = Vec::new();
    for module in MODULES {
        let text = fs::read_to_string(source.join(format!("{module}.rs")))
            .unwrap_or_else(|error| panic!("reading linux-raw-sys {module}.rs: {error}"));
        let header = format!(
            "// Generated by `cargo run -p {PACKAGE} --bin generate-linux` from linux-raw-sys \
             {version}\n// src/aarch64/{module}.rs, with guest pointers as u64. Do not edit.\n\n"
        );
        let converted = adopt_interface(
            &add_byte_derives(&drop_unsafe_methods(&convert(&text))),
            &interface,
        );
        for name in type_names(&converted) {
            structs.push(format!("{module}::{name}"));
        }
        out.push(Generated {
            path: kernel.join(format!("linux/{module}.rs")),
            contents: rustfmt(&(header + &converted)),
        });
    }
    let general = fs::read_to_string(source.join("general.rs")).expect("reading general.rs");
    out.push(Generated {
        path: kernel.join("syscall/list.rs"),
        contents: rustfmt(&syscall_list(&general, &version)),
    });
    out.push(Generated {
        path: workspace_root().join(LAYOUT_TEST),
        contents: rustfmt(&layout_test(&structs, &version)),
    });
    out
}

/// The kernel interface's folder, relative to the workspace root, and its files that define
/// Linux's numbers by name, with the module each is.
const INTERFACE_SOURCE: &str = "crates/kernel";
const INTERFACE_FILES: &[(&str, &str)] = &[
    ("signal.rs", "wcontainers_kernel::signal"),
    (
        "signal_information.rs",
        "wcontainers_kernel::signal_information",
    ),
];

/// The lines of the interface's files that name a number: an enum or a structure, a variant and
/// whether it carries fields, an associated constant, a constant, and an `impl` block.
const ITEM: &str = r"^pub (?:enum|struct) ([A-Za-z0-9_]+)";
const VARIANT: &str = r"^    ([A-Z_][A-Z0-9_]*)(?:(\(| \{)| =)";
const ASSOCIATED: &str = r"^    pub const ([A-Z_][A-Z0-9_]*): Self";
const CONSTANT: &str = r"^pub const ([A-Z_][A-Z0-9_]*): ";
const IMPL_BLOCK: &str = r"^impl ([A-Za-z0-9_]+) \{";

/// A generated constant: what comes before its value, its name, its type, and its end.
const BINDING: &str = r"(?m)^(pub const ([A-Za-z0-9_]+): ([A-Za-z0-9_]+) = ).+(;)$";

/// What joins the parts of a Rust path (rustfmt then writes it without the spaces), and what
/// casts a value to a type.
const RUST_PATH_JOIN: &str = " :: ";
const CAST: &str = " as ";

/// Every number the kernel interface names, by its name in Linux, with the expression that gives
/// it from the interface: a variant (`Signal::SIGKILL`), an associated constant (`Signal::SIGIOT`)
/// or a constant (`SI_MAX_SIZE`).
fn interface_names() -> std::collections::BTreeMap<String, String> {
    let [item, variant, associated, constant, impl_block] =
        [ITEM, VARIANT, ASSOCIATED, CONSTANT, IMPL_BLOCK]
            .map(|pattern| Regex::new(pattern).expect("regex"));
    let mut names = std::collections::BTreeMap::new();
    for (file, module) in INTERFACE_FILES {
        let path = workspace_root().join(INTERFACE_SOURCE).join(file);
        let text = fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("reading {}: {error}", path.display()));
        // An enum's variants, and whether any carries fields (so that `as` cannot give its number).
        let mut enums: Vec<(String, Vec<String>, bool)> = Vec::new();
        let mut current: Option<String> = None;
        for line in text.lines() {
            if let Some(capture) = item.captures(line) {
                current = Some(capture[1].to_owned());
                enums.push((capture[1].to_owned(), Vec::new(), false));
            } else if let Some(capture) = impl_block.captures(line) {
                current = Some(capture[1].to_owned());
            } else if let Some(capture) = constant.captures(line) {
                names.insert(
                    capture[1].to_owned(),
                    [module, RUST_PATH_JOIN, &capture[1]].concat(),
                );
            } else if let (Some(owner), Some(capture)) = (&current, associated.captures(line)) {
                let path = [module, RUST_PATH_JOIN, owner, RUST_PATH_JOIN, &capture[1]].concat();
                names.insert(capture[1].to_owned(), path);
            } else if let (Some(_), Some(capture)) = (&current, variant.captures(line)) {
                let entry = enums.last_mut().expect("a variant is inside an enum");
                entry.1.push(capture[1].to_owned());
                entry.2 |= capture.get(2).is_some();
            }
        }
        // `as` gives no number for an enum whose variants carry fields, and nothing safe does in a
        // constant: those codes keep linux-raw-sys's values, and the kernel's `siginfo` tests
        // check that the interface gives each the same number.
        for (owner, variants, _) in enums.into_iter().filter(|(_, _, with_fields)| !with_fields) {
            for name in variants {
                let path = [module, RUST_PATH_JOIN, &owner, RUST_PATH_JOIN, &name].concat();
                names.insert(name, path);
            }
        }
    }
    names
}

/// Gives every constant the kernel interface also names the interface's value, so that a number
/// is defined once.
fn adopt_interface(text: &str, names: &std::collections::BTreeMap<String, String>) -> String {
    let binding = Regex::new(BINDING).expect("regex");
    binding
        .replace_all(text, |capture: &regex::Captures| {
            let (whole, [start, name, kind, end]) = capture.extract();
            match names.get(name) {
                Some(path) => [start, path, CAST, kind, end].concat(),
                None => whole.to_owned(),
            }
        })
        .into_owned()
}

/// Formats Rust source as `cargo fmt` would, so generated files stay unchanged by it.
fn rustfmt(source: &str) -> String {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .expect("running rustfmt");
    child
        .stdin
        .take()
        .expect("stdin")
        .write_all(source.as_bytes())
        .expect("writing to rustfmt");
    let output = child.wait_with_output().expect("rustfmt");
    assert!(output.status.success(), "rustfmt failed");
    String::from_utf8(output.stdout).expect("rustfmt output is UTF-8")
}

/// Rewrites one bindings file so its layouts hold on every target.
fn convert(text: &str) -> String {
    let pointer = Regex::new(r"\*(?:mut|const) [A-Za-z0-9_:]+").expect("regex");
    let function =
        Regex::new(r#"::core::option::Option<unsafe extern "C" fn\([^)]*\)(?: -> [^>]+)?>"#)
            .expect("regex");
    let declaration = Regex::new(r"^pub (?:type [A-Za-z0-9_]+ = |[A-Za-z0-9_]+: )").expect("regex");
    let size = Regex::new(r"^(pub [A-Za-z0-9_]+: )(?:usize|isize),").expect("regex");
    let mut out = String::with_capacity(text.len());
    for line in text.lines() {
        let mut line = line.replace("crate::ctypes::", "super::ctypes::");
        if declaration.is_match(&line) {
            line = function.replace_all(&line, "u64").into_owned();
            loop {
                let next = pointer.replace_all(&line, "u64").into_owned();
                if next == line {
                    break;
                }
                line = next;
            }
            line = size.replace(&line, "${1}u64,").into_owned();
        }
        out.push_str(&line);
        out.push('\n');
    }
    out
}

/// Drops every method that holds `unsafe` from the bindings' `impl` blocks, and every block left
/// empty: bindgen's raw bitfield accessors, its bitfield getters and setters (which transmute), and
/// its views of a flexible array or a union field. Nothing calls them, and the kernel's crate
/// forbids unsafe code. The bitfields stay readable through `__BindgenBitfieldUnit`'s safe `get`
/// and `set`.
fn drop_unsafe_methods(text: &str) -> String {
    let word = Regex::new(r"\bunsafe\b").expect("regex");
    let mut out = String::with_capacity(text.len());
    // The `impl` block being read: its opening lines, its members kept, and the member being read.
    let mut header = String::new();
    let mut kept = String::new();
    let mut member = String::new();
    let mut in_impl = false;
    let mut depth = 0usize;
    for line in text.lines() {
        let before = depth;
        for character in line.chars() {
            match character {
                '{' | '(' | '[' => depth += 1,
                '}' | ')' | ']' => depth -= 1,
                _ => {}
            }
        }
        if before == 0 && !in_impl {
            if line.starts_with("impl") && depth == 0 && !line.ends_with('}') {
                // An `impl` whose `where` clause runs over more lines.
                in_impl = true;
                header = format!("{line}\n");
                continue;
            }
            if line.starts_with("impl") && depth == 1 {
                in_impl = true;
                header = format!("{line}\n");
                continue;
            }
            out.push_str(line);
            out.push('\n');
            continue;
        }
        if !in_impl {
            out.push_str(line);
            out.push('\n');
            continue;
        }
        if before == 0 {
            // The rest of a long `impl` line, up to its opening brace.
            header.push_str(line);
            header.push('\n');
            continue;
        }
        if depth == 0 {
            // The block's closing brace.
            if !kept.is_empty() {
                out.push_str(&header);
                out.push_str(&kept);
                out.push_str(line);
                out.push('\n');
            }
            header.clear();
            kept.clear();
            in_impl = false;
            continue;
        }
        member.push_str(line);
        member.push('\n');
        if depth == 1 && !line.starts_with("#[") {
            if !word.is_match(&member) {
                kept.push_str(&member);
            }
            member.clear();
        }
    }
    assert!(depth == 0 && !in_impl && member.is_empty(), "unbalanced bindings");
    out
}

/// Gives the structures in [`BYTES`] zerocopy's derives.
fn add_byte_derives(text: &str) -> String {
    let item = Regex::new(r"#\[derive\(Debug, Copy, Clone\)\]\npub struct ([A-Za-z0-9_]+) \{")
        .expect("regex");
    item.replace_all(text, |capture: &regex::Captures| {
        let name = &capture[1];
        if BYTES.contains(&name) {
            format!(
                "#[derive(Debug, Copy, Clone, zerocopy::FromBytes, zerocopy::IntoBytes, \
                 zerocopy::Immutable, zerocopy::KnownLayout)]\npub struct {name} {{"
            )
        } else {
            capture[0].to_string()
        }
    })
    .into_owned()
}

/// Names of the non-generic structures and unions in a bindings file.
fn type_names(text: &str) -> Vec<String> {
    let item = Regex::new(r"(?m)^pub (?:struct|union) ([A-Za-z0-9_]+)\s*\{").expect("regex");
    item.captures_iter(text)
        .map(|capture| capture[1].to_string())
        .collect()
}

/// The list of every ARM64 system call, by number and name.
fn syscall_list(general: &str, version: &str) -> String {
    let constant = Regex::new(r"(?m)^pub const __NR_([a-z0-9_]+): u32 = ([0-9]+);").expect("regex");
    let mut calls: Vec<(u32, String)> = constant
        .captures_iter(general)
        .map(|capture| (capture[2].parse().expect("number"), capture[1].to_string()))
        .collect();
    calls.sort();
    let mut out = format!(
        "// Generated by `cargo run -p {PACKAGE} --bin generate-linux` from linux-raw-sys \
         {version}\n// src/aarch64/general.rs. Do not edit.\n\n\
         //! Every ARM64 Linux system call, by number and name.\n\n\
         use crate::linux::general::*;\n\n\
         pub(crate) const LIST: [(u32, &str); {}] = [\n",
        calls.len()
    );
    for (_, name) in &calls {
        out.push_str(&format!("    (__NR_{name}, \"{name}\"),\n"));
    }
    out.push_str("];\n");
    out
}

/// A test that every copied structure has linux-raw-sys's size and alignment on an ARM64 host.
fn layout_test(structs: &[String], version: &str) -> String {
    let mut out = format!(
        "// Generated by `cargo run -p {PACKAGE} --bin generate-linux` from linux-raw-sys \
         {version}. Do not edit.\n\n\
         //! Every structure the kernel copied from linux-raw-sys has the original's size and alignment.\n\n\
         #![cfg(target_arch = \"aarch64\")]\n\n\
         use core::mem::{{align_of, size_of}};\n\n\
         #[test]\n\
         fn layouts_match_linux_raw_sys() {{\n"
    );
    for name in structs {
        out.push_str(&format!(
            "    assert_eq!(size_of::<wcontainers_kernel_linux::linux::{name}>(), size_of::<linux_raw_sys::{name}>(), \"{name}\");\n\
             \x20   assert_eq!(align_of::<wcontainers_kernel_linux::linux::{name}>(), align_of::<linux_raw_sys::{name}>(), \"{name}\");\n"
        ));
    }
    out.push_str("}\n");
    out
}
