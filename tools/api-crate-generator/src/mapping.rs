//! The mapping rule: each C form of the metadata and the one safe Rust form it becomes (MAPPING.md, row by row).
//! The generator counts every use of each row and lists every parameter or field no row maps.

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Row {
    Scalar,
    Bool,
    Enumeration,
    Handle,
    Guid,
    StructureByValue,
    StructureIn,
    StructureInOut,
    ValueOut,
    ObjectIn,
    BaseObjectIn,
    UnknownIn,
    ObjectOut,
    BaseObjectOut,
    InterfaceById,
    ArrayIn,
    ArrayFixedIn,
    ArrayOut,
    ArrayOutCounted,
    BytesIn,
    BytesOut,
    BytesOutCounted,
    StringIn,
    WideStringIn,
    CountDropped,
    StatusResult,
    FixedArrayField,
    BytesField,
    ArrayField,
    StringField,
    ObjectField,
    UnionField,
    LargeInteger,
    Unmapped,
}

impl Row {
    pub const ALL: [Row; 34] = [
        Row::Scalar,
        Row::Bool,
        Row::Enumeration,
        Row::Handle,
        Row::Guid,
        Row::StructureByValue,
        Row::StructureIn,
        Row::StructureInOut,
        Row::ValueOut,
        Row::ObjectIn,
        Row::BaseObjectIn,
        Row::UnknownIn,
        Row::ObjectOut,
        Row::BaseObjectOut,
        Row::InterfaceById,
        Row::ArrayIn,
        Row::ArrayFixedIn,
        Row::ArrayOut,
        Row::ArrayOutCounted,
        Row::BytesIn,
        Row::BytesOut,
        Row::BytesOutCounted,
        Row::StringIn,
        Row::WideStringIn,
        Row::CountDropped,
        Row::StatusResult,
        Row::FixedArrayField,
        Row::BytesField,
        Row::ArrayField,
        Row::StringField,
        Row::ObjectField,
        Row::UnionField,
        Row::LargeInteger,
        Row::Unmapped,
    ];

    /// The C form and the Rust form, as MAPPING.md states the row.
    pub fn statement(self) -> &'static str {
        match self {
            Row::Scalar => "integer or float by value -> the same Rust primitive",
            Row::Bool => "BOOL -> bool (any nonzero is true)",
            Row::Enumeration => "C enum or flags -> a newtype over its integer, its values as constants",
            Row::Handle => "handle typedef (HWND, HMODULE, HANDLE, ...) -> a newtype over usize",
            Row::Guid => "GUID, REFGUID, REFIID -> Guid, &Guid",
            Row::StructureByValue => "struct by value -> the struct",
            Row::StructureIn => "const struct pointer (_In_, _In_opt_) -> &T, Option<&T>",
            Row::StructureInOut => "struct pointer _Inout_ -> &mut T",
            Row::ValueOut => "_Out_ pointer to a value -> the value, returned",
            Row::ObjectIn => "interface pointer in -> &the object kind's associated type (Option for _opt_)",
            Row::BaseObjectIn => "pointer to an interface several kinds derive from -> <Interface>Ref enum of those kinds",
            Row::UnknownIn => "IUnknown pointer in -> UnknownRef enum: the API's kinds, or Unknown",
            Row::ObjectOut => "_COM_Outptr_ -> the owned object kind, returned; an _Out_ of an object not made -> Option",
            Row::BaseObjectOut => "out pointer to a base interface -> <Interface>Object enum of the kinds, returned",
            Row::InterfaceById => "REFIID riid + void** ppv -> &Guid in, the API's Object enum returned",
            Row::ArrayIn => "_In_reads_(n) array + its count -> &[T], the count dropped",
            Row::ArrayFixedIn => "array of a fixed count -> &[T; N]",
            Row::ArrayOut => "_Out_writes_(n) array, n given in -> n kept, Vec<T> returned",
            Row::ArrayOutCounted => "_Out_writes_ array whose count is an _Inout_ pointer -> Vec<T> returned, count dropped",
            Row::BytesIn => "const void* + byte count -> &[u8], copied once by the serving glue",
            Row::BytesOut => "void* _Out_writes_bytes_(n) -> &impl VolatileBytes, n dropped (its len)",
            Row::BytesOutCounted => "void* out + _Inout_ size -> Option<&impl VolatileBytes>, the size returned",
            Row::StringIn => "PCSTR in -> &CStr",
            Row::WideStringIn => "PCWSTR in -> &[u16] (no terminator)",
            Row::CountDropped => "a count another parameter's annotation names -> dropped (the slice's len)",
            Row::StatusResult => "HRESULT return -> Result<outs, HResult>",
            Row::FixedArrayField => "fixed array field -> [T; N]",
            Row::BytesField => "void pointer field -> Vec<u8>, length from an exception line",
            Row::ArrayField => "pointer field with a count field -> Vec<T>",
            Row::StringField => "PCSTR field -> CString",
            Row::ObjectField => "interface pointer field -> Option<owned object kind>, the struct generic over the API",
            Row::UnionField => "C union -> a struct of every member, each read from the same bytes",
            Row::LargeInteger => "LARGE_INTEGER -> i64",
            Row::Unmapped => "no row: written as &impl VolatileBytes (caller bytes) or Vec<u8>, and listed",
        }
    }
}
